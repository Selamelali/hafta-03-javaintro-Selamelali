public class DaireHesap {
    public static void main(String[] args) {
        double r = 5.5;
        double alan = Math.PI * r * r;         // πr²
        double cevre = 2 * Math.PI * r;        // 2πr
        
        System.out.println("Yarıçap : " + r);
        System.out.println("Alan : " + alan);
        System.out.println("Çevre : " + cevre);
    }
}
